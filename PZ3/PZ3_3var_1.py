#Вариант 3.
#1. Дано целое число A. Проверить истинность высказывания: «Число A является
#четным».
try: #Обработка исключений
    A = int(input("Введите целое число:")) #Ввод целого числа
    if A % 2 == 0: #проверка условия
        print("Число", A, "является четным")
    else: #Если условие не выполнено
        print("Число", A, "не является четным")
except ValueError:
    print("Ошибка, повторите попытку заново")

