#1. Дано вещественное число — цена 1 кг конфет. Вывести стоимость 1, 2, ..., 10 кг
#конфет.
konf = input("Введите цену 1 кг конфет: ") #Ввод значений
kg = 1
while type(konf) !=float: #обработка исключений
    try:
        konf = float(konf)
    except ValueError:
        print("Ошибка, попробуйте снова")
        konf = input("Введите цену 1 кг конфет: ")
while kg <= 10: #Выполнение условий задачи
    stoim = kg*konf
    print("Стоимость" , kg, "кг конфет =" , stoim)
    kg += 1