#1. Дан первый член A и разность D арифметической прогрессии. Сформировать и
#вывести список размера 10, содержащий 10 первых членов данной прогрессии: A, A
#+ D, A + 2*D, A + 3*D, ... .
A = input("Введите первый член арифметической прогресии: ")
while type(A) != int : #обработка исключений
    try:
        A = int(A)
    except ValueError:
        print("Ошибка, попробуйте снова")
        A = input("Введите первый член арифметической прогресии: ")
D = input("Введите разность арифметической прогресии: ")
while type(D) != int : #обработка исключений
    try:
        D = int(D)
    except ValueError:
        print("Ошибка, попробуйте снова")
        D = input("Введите разность арифметической прогресии: ")
Spis =[] #Ввод пустого списка
for i in range(10): #цикл for для записывания 10 членов в список
    C = A + i * D
    Spis.append(C)
print(Spis)